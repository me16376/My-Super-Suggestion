const fs = require('fs');
const path = require('path');

const prelimDir = path.resolve(__dirname, '../data/preliminary');
const mathPath = path.join(prelimDir, 'math_mcq.json');
const currentMath = JSON.parse(fs.readFileSync(mathPath, 'utf8'));

console.log('=== PURIFYING MATH & MENTAL ABILITY DATASET ===');
console.log('Current count before purification:', currentMath.length);

// 1. Filter out repetitive template questions
const cleanMath = currentMath.filter(q => {
  const isRepetitiveSumDiff = q.question.includes('দুটি সংখ্যার যোগফল') && q.question.includes('বিয়োগফল');
  return !isRepetitiveSumDiff;
});

console.log('Genuine baseline math questions retained:', cleanMath.length);

const finalMath = [...cleanMath];
const seen = new Set(cleanMath.map(q => q.question.toLowerCase().trim()));

function addQ(topic, q, opts, ans, exp, tags) {
  const norm = q.toLowerCase().trim();
  if (!seen.has(norm)) {
    seen.add(norm);
    finalMath.push({
      subject: "সাধারণ গণিত ও মানসিক দক্ষতা",
      topic,
      question: q.trim(),
      options: opts,
      answer: ans,
      explanation: exp.trim(),
      tags: tags || ["buet_math", "real_problem"]
    });
  }
}

